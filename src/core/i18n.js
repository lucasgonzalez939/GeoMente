export function normalizeLocale(locale) {
  return locale === "es" ? "es" : "en";
}

export function t(locale, key, vars = {}) {
  const active = normalizeLocale(locale);
  const template = MESSAGES[active][key] ?? MESSAGES.en[key] ?? key;
  return Object.entries(vars).reduce(
    (text, [name, value]) => text.replaceAll(`{${name}}`, String(value)),
    template,
  );
}

export function localizeChallenge(challenge, locale) {
  if (normalizeLocale(locale) !== "es") return challenge;
  const translated = ES_CHALLENGE_TRANSLATIONS[challenge.id];
  if (!translated) return challenge;
  return {
    ...challenge,
    ...translated,
    hints: [...translated.hints],
    misconceptions: [...translated.misconceptions],
  };
}

export function formatConcepts(concepts, locale) {
  return concepts.map((concept) => t(locale, `concept.${concept}`)).join(", ");
}

export function formatChallengeLevel(challenge, locale) {
  return t(locale, "challenge.levelFormat", {
    level: t(locale, `level.${challenge.level}`),
    concepts: formatConcepts(challenge.concept, locale),
    difficulty: challenge.difficulty,
  });
}

export function formatHistoryTimestamp(timestamp, locale) {
  const normalized = normalizeLocale(locale) === "es" ? "es-ES" : "en-US";
  return new Intl.DateTimeFormat(normalized, { dateStyle: "short", timeStyle: "short" }).format(timestamp);
}
